///
/// ponytail: 앱 안 낱말 목록이라 변형(초성 섞기·유사 글자)은 다 못 잡는다.
/// 우회가 잦아지면 서버(Functions 트리거)에서 검사하고 목록을 원격으로 관리한다.
const _words = [
  // 욕설
  '씨발', '시발', '씨바', '씨팔', '시팔', 'ㅅㅂ', 'ㅆㅂ', '씹새', '씹년', '씹할', '좆', 'ㅈ같',
