  '개새끼', '개새기', '개색기', '개색히', '개세끼', '새끼야',
  '미친놈', '미친년', '미친새', '또라이', '꺼져라',
  '니애미', '느금마', '니미럴', '엠창', '애미뒤', '애비뒤',
  // 비하·혐오
  '애자새', '장애새', '한남충', '김치녀', '틀딱', '짱깨', '쪽바리', '흑형',
  // 영어
  'fuck', 'shit', 'bitch', 'asshole', 'nigger',
];

/// 욕설과 글자가 겹치는 보통 낱말. 먼저 지우고 본다.
const _innocent = ['시발점', '시발역'];

/// 낱말 사이에 끼워 넣은 띄어쓰기·숫자·기호(씨 발, 씨.발, 씨1발)는 지우고 본다.
final _noise = RegExp(r'[^가-힣ㄱ-ㅎㅏ-ㅣa-z]');

bool containsProfanity(String text) {
  var plain = text.toLowerCase().replaceAll(_noise, '');
  for (final word in _innocent) {
    plain = plain.replaceAll(word, '');
  }
  return _words.any(plain.contains);
}

